/** Блок «Очки в рейтинге» для окна настроек игры (или null — бета не открыта, игры нет в рейтинге). */
export function pointsInfo(api, id) {
  if (!api?.feature?.('rating-points')) return null;
  const info = POINTS_INFO[id];
  if (!info) return null;
  return el('div', { class: 'pts-info' },
    el('b', { class: 'pts-info-title' }, '🏆 Очки в рейтинге'),
    info.lines.map((text) => el('p', {}, text)),
    info.sum && el('p', { class: 'pts-info-note' }, 'Очки копятся за всё время — место в рейтинге по их сумме.'),
  );
}
