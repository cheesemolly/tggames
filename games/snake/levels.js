export const MAP_COUNT = MAPS.length;
export const mapTitle = (level) => MAPS[(level - 1) % MAPS.length].title;
export const cycleOf = (level) => Math.floor((level - 1) / MAPS.length) + 1;

/** Карта уровня в виде, который понимает logic.newGame. */
export function levelMap(level) {
  const def = MAPS[(level - 1) % MAPS.length];
  const cycle = cycleOf(level) - 1;
  const cols = LEVEL_COLS;
  const rows = LEVEL_ROWS;
  const at = (x, y) => y * cols + x;
  const walls = [];
  const portalCells = {};
  const spikes = [];
  let start = null;
  def.map.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      const i = at(x, y);
      if (ch === '#') walls.push(i);
      else if (ch === 'S') start = { x, y, dir: def.start };
      else if (ch === '^' || ch === '*') {
        const { period, on } = def.spikes;
        spikes.push({ idx: i, period, on, offset: ch === '*' ? Math.floor(period / 2) : 0 });
      } else if (/[a-z]/.test(ch)) (portalCells[ch] ??= []).push(i);
    });
  });
  const portals = Object.entries(portalCells).map(([id, [a, b]]) => ({ id, a, b }));
  const movers = (def.movers ?? []).map((m) => {
    const [x1, y1] = m.from;
    const [x2, y2] = m.to;
    const n = Math.max(Math.abs(x2 - x1), Math.abs(y2 - y1));
    const path = Array.from({ length: n + 1 }, (_, k) => at(x1 + Math.sign(x2 - x1) * k, y1 + Math.sign(y2 - y1) * k));
    return { path, pos: 0, step: 1, every: m.every };
  });
  return {
    title: def.title,
    cols,
    rows,
    walls,
    start,
    portals,
    spikes,
    movers,
    goal: def.goal + cycle * 4,
    pace: def.pace * (1 + cycle * 0.08),
    raw: def.map,
  };
}
