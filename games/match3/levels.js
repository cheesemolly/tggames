/** Описание уровня n (1…100) для newGame. */
export function levelSpec(n) {
  const [layout, colors, goals, extra = {}] = RAW[n - 1];
  const cols = Math.max(...layout.map((row) => row.length));
  const tune = TUNING[n - 1];
  return {
    level: n,
    rows: layout.length,
    cols,
    layout: layout.map((row) => row.padEnd(cols, '_')),
    colors,
    goals: G(goals),
    moves: tune?.moves ?? extra.moves ?? 30,
    boss: Boolean(extra.boss),
    tip: extra.boss ? 'boss' : extra.tip ?? null,
    treasure: extra.treasure ?? null,
    timer: extra.timer ?? null,
    chapter: Math.floor((n - 1) / 10),
  };
}

