function parse([id, rows, weight]) {
  const cells = [];
  rows.forEach((row, r) => [...row].forEach((ch, c) => {
    if (ch === '#') cells.push([r, c]);
  }));
  return { id, cells, weight, rows: rows.length, cols: Math.max(...rows.map((r) => r.length)) };
}

export const SHAPES = RAW.map(parse);
export const SHAPE_BY_ID = Object.fromEntries(SHAPES.map((s) => [s.id, s]));

