/** SVG-разметка фигуры: type 1–6, black — чёрная, style — 'classic' | 'flat'. */
export function pieceSvg(type, black, style = 'classic') {
  const s = SHAPES[LETTERS[type]];
  const side = black ? 'b' : 'w';
  const outline = style === 'flat' ? 'none' : `var(--ch-${side}-line)`;
  return `<svg viewBox="0 0 45 45" aria-hidden="true" class="ch-svg ch-svg-${style}">`
    + `<path d="${s.body}" fill="var(--ch-${side}-fill)" stroke="${outline}" stroke-width="1.5" stroke-linejoin="round"/>`
    + (s.detail ? `<path d="${s.detail}" fill="none" stroke="var(--ch-${side}-detail)" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/>` : '')
    + '</svg>';
}

