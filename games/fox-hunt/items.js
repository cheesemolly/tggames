/** Сколько секунд действуют эликсиры (что именно они меняют — в EFFECTS ниже). */
export const POTION_TIME = { haste: 30, rage: 30, stone: 60 };

// Эликсир включает временное действие id. Пока оно ещё идёт, пить незачем: второе с первым не складывается,
// а каменная шкура к тому же не вернула бы уже сбитые щиты.
function elixir(G, id) {
  if (G.player.fx[id] > 0) {
    toast(G, `${EFFECTS[id].name} ещё действует`);
    return false;
  }
  return addEffect(G, id, POTION_TIME[id]);
}

