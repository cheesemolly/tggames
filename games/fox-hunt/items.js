// Вещи «Лисьей охоты»: броня, украшения, зелья, дары леса и временные действия. Почти всё — данные: вещь
// меняет характеристики лисы через add / mul / flags, а код под отдельную вещь не пишется.
//
// ── КАК ВЕЩЬ МЕНЯЕТ ЛИСУ ─────────────────────────────────────────────────────────────────────────────────────
//   add:   { ключ: число }   прибавить к характеристике          итог = (основа + все add) × все mul,
//   mul:   { ключ: число }   умножить её                          потом пределы из balance.js (LIMITS)
//   flags: { имя: значение } включить умение
//
// Характеристики (в скобках — основа):
//   maxHp (5) сердца · maxShield (0) щит · maxMana (100) · manaRegen (0) маны в секунду · speed (132)
//   dashDmg (4) урон рывка · dashDist (148) длина · dashDur (0.17) время · dashCd (0.55) перезарядка заряда ·
//   dashCharges (1) · iframes (0.06) неуязвимость после рывка · crit (0.05) шанс двойного урона · luck (0) ·
//   coinMul (1) · magnet (34) радиус подбора · wDmg (1) урон оружия · wCd (1) его перезарядка (меньше — чаще) ·
//   wCost (1) расход маны · wRange (1) дальность · shotSpeed (1) · healBonus (0) прибавка к любому лечению ·
//   aware (1) с какого расстояния добыча замечает лису (меньше — позже) · rabbitsPlus (0) добыча в волне ·
//   rabbitPts (0) очки за добычу · shopMul (1) цены · palSlots (2) мест для спутников · palHp (1) их здоровье ·
//   hazardCut (0) на сколько меньше бьют красные зоны (не ниже 1) · shieldRegen (1) скорость возврата щита ·
//   dodge (0) шанс увернуться · preyStay (1) сколько добыча не уходит · warn (0) на сколько секунд раньше видны
//   красные зоны.
//
// Флаги (true — умение со значением по умолчанию; у числовых можно написать своё число):
//   fireTrail — рывок оставляет огненный след          iceDash — рывок замораживает задетых на секунду
//   slowDash — рывок замедляет задетых на 2 с          shockwave — удар по земле там, где лиса приземлилась
//   thorns (3) — урон зверю, ударившему касанием       contact (1) — урон зверю, который трётся о лису
//   roomBlock (1) — столько ударов за комнату не проходит        revive — раз за партию вещь сгорает вместо жизни
//   sporeOnHit — при ударе по лисе вокруг ядовитое облако        dupShot (0.15) — шанс двойного выстрела
//   killHeal (12) — каждые столько убитых врагов одно сердце     coinPerRabbit (1) — монет за каждую добычу
//   revealMap — вся карта локации открыта              kbImmune — лису не отбрасывает
//   slowImmune — грязь, лёд и паутина не замедляют     cloudImmune — не страшны яд, огонь и паутина на земле
//   floorImmune — не страшны грязь, лёд, колючки, горячие трещины и капканы
//   projSlow (0.3) — вражеские выстрелы медленнее на эту долю    glowbug — светлячок бьёт ближнего врага
//   manaPerRabbit (3) — маны за каждую добычу          secondWind — после потери жизни ускорение и два щита
// Нового флага данными не завести: его должен понимать движок (player.js, FLAG_RULES).
//
// ── ЗАПИСИ ───────────────────────────────────────────────────────────────────────────────────────────────────
//   ARMOR.vest       = { name, rarity, shield, desc, add?, mul?, flags? }      shield — сколько щита даёт
//   ACCESSORIES.fang = { name, rarity, desc, add?, mul?, flags? }
//   POTIONS.heal     = { name, rarity, desc, use(G) }      use вернула false — пить незачем, зелье не тратится
//   GIFTS.vigor      = { name, desc, add?, mul?, flags?, onTake?(G), once?, offer? }   onTake — разово при выборе;
//                          once: true — второй раз не предлагать; offer: false — не предлагать вовсе: такой «дар»
//                          выдаёт место через takeGift (плата ворону — сердце насовсем: add: { maxHp: -1 })
//   EFFECTS.haste    = { name, add?, mul?, flags? }        временное действие; включают его addEffect(G, id, сек)
// rarity: 0 обычное, 1 редкое, 2 эпическое, 3 легендарное. name — до 22 знаков, без точки. desc — одна короткая
// фраза для карточки, до 70 знаков, с числом, которое понятно игроку («на 20 % быстрее», «ещё один заряд»).
// drop: false — вещь не выпадает и не продаётся сама (её выдаёт место).
// id вещи один на все четыре вида (оружие, броня, украшения, зелья): повтор — ошибка при запуске.
//
// Пример с разбором:
//   moonrobe: {
//     name: 'Лунная мантия', rarity: 2,
//     shield: 2,                              // два щита
//     desc: 'Два щита возвращаются вдвое быстрее, запас маны больше на 20.',
//     add: { maxMana: 20 },                   // +20 к запасу маны
//     mul: { shieldRegen: 2 },                // щит восстанавливается вдвое быстрее
//   }
//
// Что можно звать из use и onTake:
//   из player.js: heal(G, n) → сколько вылечено, addMana(G, n), addEffect(G, 'haste' | 'rage' | 'stone' | своё, сек),
//                 gainCoins(G, n), recalc(G);
//   из core.js: sfx(G, 'heal'), toast(G, 'текст'), floatText(G, x, y, 'текст'); G.player — лиса (hp, mana, st.maxHp…),
//   G.map.rooms — комнаты карты (r.seen = true — открыть на мини-карте).
//
// ── КАК ПОДОБРАНЫ ЧИСЛА ──────────────────────────────────────────────────────────────────────────────────────
// Что считается штуками (сердца, щиты, заряды, мана, кролики, очки) и шансы — прибавляется (add): две вещи дают
// ровно вдвое больше одной, а верхний предел держит движок. Скорость, длина рывка, перезарядки, расход маны и
// цены — умножаются (mul): «на 20 % быстрее» остаётся правдой при любых других вещах, а две скидки подряд
// никогда не доведут перезарядку или цену до нуля. Ни одна вещь не делает лису вдвое сильнее; самое сильное —
// эпическое или легендарное. Редкости брони и украшений вместе: около 40 % обычных, 30 % редких, 20 %
// эпических, 10 % легендарных. Среди зелий лечение стоит первым и остаётся обычным: оно попадается чаще всех.

