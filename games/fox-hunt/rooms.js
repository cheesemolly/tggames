//   w, h    — размер в клетках вместе со стеной: S 17×11, M 21×13, L 25×15 (у хозяина — только L);
//   weight  — как часто выпадает среди подходящих (по умолчанию 1); minFloor — с какой локации;
//   place   — только для kind 'place': id места из places.js, для которого шаблон (например 'shop').
//             Без place шаблон годится любому месту.
//
// Буквы:
//   #  стена (весь край — стена)            .  земля          ,  тропинка (та же земля, для красоты)
//   T  высокое: дерево, скала — не пройти, не прострелить, не перепрыгнуть
//   o  низкое: пень, валун — не пройти, но выстрел и рывок проходят поверх
//   b  куст — как низкое, но рывок (или два попадания) его ломает, иногда выпадает монета
//   ~  вода / прорубь / яма — не пройти, рывком перепрыгнуть можно
//   ^  колючки — ходить можно, но больно (единица урона в секунду)
//   =  особая земля места: высокая трава (лес, осень), грязь (болото), лёд (зима), горячая трещина (пещера)
//   B  кроличья нора: отсюда кролики выходят и сюда убегают
//   R  лисья нора — точка возрождения (нужна хотя бы одна)
//   S  где появляются враги             C  середина: главный предмет места (сундук, торговец, портал)
//   1…5  места под предметы: прилавки торговца, кандидаты в привале, таблички
//
// Дверей в шаблоне нет: их ставит карта — проём в три клетки посередине стороны, где есть сосед. Поэтому три
// клетки перед серединой КАЖДОЙ стороны должны быть свободны («.» или «,»). Комнату могут отразить по
// горизонтали и вертикали — не рассчитывайте на «лево» и «право».
//
// Правила (проверяет тест world.test.js для каждого шаблона, функция validateTemplate из world.js):
// прямоугольник нужного размера, край — стена, всё проходимое связано между собой и со всеми четырьмя входами,
// есть R; у охотничьей — не меньше трёх B, трёх S и 55 % свободного места.
//
// Пример с разбором — первый шаблон ниже.
//
// MODS — особые условия комнаты (редко; о них объявляет плашка): { name, text, … }. Движок понимает поля:
//   preyMul   — во сколько раз больше добычи в волне («Изобилие» — 2);
//   preyPlus  — сколько добычи добавить в волну;
//   preyPts   — сколько очков добавить за каждую добычу («Ночь» — 1);
//   noHazards — напастей нет («Тишина»);
//   hazards   — id напастей из hazards.js, которые бьют здесь сверх обычных («Гроза» — ['lightning']);
//   hazardMul — во сколько раз чаще бьют напасти;
//   weight, minFloor — как часто и с какой локации;
//   apply(G, room) — что сделать при входе в комнату; step(G, room, dt) — что делать каждый шаг.
// Остальное (туман, темнота) — дело рисования: оно смотрит room.mod.

