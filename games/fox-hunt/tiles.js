// Клетки комнаты «Лисьей охоты»: коды, буквы шаблонов и что клетка пропускает. Общий файл логики и рисунков —
// без DOM и без зависимостей.
//
// Комната — сетка клеток T×T единиц мира; по краю — стена. Шаблон комнаты записан строками букв (rooms.js),
// в памяти — массив кодов. Дверей в шаблоне нет: проём (три клетки посередине стороны) ставит карта локации.

export const T = 32;

export const TILE = {
  FLOOR: 0,     // земля
  PATH: 1,      // тропинка — та же земля, только вытоптана
  WALL: 2,      // край комнаты: стена леса, скала
  TALL: 3,      // высокое: дерево, скала, сталагмит — не пройти, не прострелить, не перепрыгнуть
  LOW: 4,       // низкое: пень, валун, бревно — не пройти, но выстрел и рывок проходят поверх
  BUSH: 5,      // куст — как низкое, но рывок (или два попадания) его ломает
  WATER: 6,     // вода / прорубь / яма — не пройти, рывком перепрыгнуть можно
  THORN: 7,     // колючки — ходить можно, но больно
  SPECIAL: 8,   // особая земля места: высокая трава и листья (лес, осень), грязь (болото), лёд (зима), горячая трещина (пещера)
  BURROW: 9,    // кроличья нора — отсюда кролики выходят и сюда убегают
  DEN: 10,      // лисья нора — точка возрождения
  DOOR: 11,     // проём в стене: открыт или закрыт — решает комната
};

// что клетка не пропускает
export const F_WALK = 1;    // пешком
export const F_SHOT = 2;    // выстрел
export const F_LEAP = 4;    // рывок (в прыжке)

/** Преграды клетки по её коду (закрытая дверь — как стена, открытая — как земля: это решает комната). */
export const BLOCK = new Uint8Array(12);
BLOCK[TILE.WALL] = F_WALK | F_SHOT | F_LEAP;
BLOCK[TILE.TALL] = F_WALK | F_SHOT | F_LEAP;
BLOCK[TILE.LOW] = F_WALK;
BLOCK[TILE.BUSH] = F_WALK;
BLOCK[TILE.WATER] = F_WALK;

/** Буква шаблона → код клетки. Метки S, C и 1…5 — обычная земля: где они стояли, комната запоминает отдельно. */
export const CHAR = {
  '#': TILE.WALL,
  '.': TILE.FLOOR,
  ',': TILE.PATH,
  T: TILE.TALL,
  o: TILE.LOW,
  b: TILE.BUSH,
  '~': TILE.WATER,
  '^': TILE.THORN,
  '=': TILE.SPECIAL,
  B: TILE.BURROW,
  R: TILE.DEN,
  S: TILE.FLOOR,
  C: TILE.FLOOR,
  1: TILE.FLOOR,
  2: TILE.FLOOR,
  3: TILE.FLOOR,
  4: TILE.FLOOR,
  5: TILE.FLOOR,
};

/** Метки шаблона, которые не становятся клеткой, а запоминаются как места. */
export const MARKS = ['S', 'C', '1', '2', '3', '4', '5'];

/** Места (биомы) по порядку локаций: после пятой — снова с первой, но труднее. */
export const BIOMES = ['forest', 'swamp', 'taiga', 'cave', 'autumn'];
export const BIOME_NAMES = {
  forest: 'Опушка',
  swamp: 'Болото',
  taiga: 'Зимний бор',
  cave: 'Пещеры',
  autumn: 'Осенняя чаща',
};

/** Размеры комнат в клетках (вместе со стеной по краю). */
export const SIZES = { S: [17, 11], M: [21, 13], L: [25, 15] };

/** Середина клетки в единицах мира. */
export const tileX = (tx) => tx * T + T / 2;
export const tileY = (ty) => ty * T + T / 2;
