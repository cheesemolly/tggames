// Раскладки маджонга. Координаты — в «половинках плитки»: плитка в (x, y, z) занимает клетки x..x+1, y..y+1
// на уровне z (так можно сдвигать плитку на полплитки, как верхушку «Черепахи»).
// Раскладки рассчитаны на вертикальный экран телефона: ширина — до 8 плиток.
// Уровень задаётся картинкой: '#' — плитка; dx/dy — сдвиг всего уровня в половинках.

function level(rows, z, dx = 0, dy = 0) {
  const out = [];
  rows.forEach((row, r) => [...row].forEach((ch, c) => {
    if (ch === '#') out.push({ x: c * 2 + dx, y: r * 2 + dy, z });
  }));
  return out;
}

const full = (w, h) => Array.from({ length: h }, () => '#'.repeat(w));

// Классическая «Черепаха» (144 плитки), транспонированная под вертикальный экран: строки → столбцы.
function turtle() {
  const tiles = [];
  const rows = [[0, 2, 24], [2, 6, 20], [4, 4, 22], [6, 2, 24], [8, 2, 24], [10, 4, 22], [12, 6, 20], [14, 2, 24]];
  for (const [y, x0, x1] of rows) for (let x = x0; x <= x1; x += 2) tiles.push({ x, y, z: 0 });
  tiles.push({ x: 0, y: 7, z: 0 }, { x: 26, y: 7, z: 0 }, { x: 28, y: 7, z: 0 });
  for (let x = 8; x <= 18; x += 2) for (let y = 2; y <= 12; y += 2) tiles.push({ x, y, z: 1 });
  for (let x = 10; x <= 16; x += 2) for (let y = 4; y <= 10; y += 2) tiles.push({ x, y, z: 2 });
  for (let x = 12; x <= 14; x += 2) for (let y = 6; y <= 8; y += 2) tiles.push({ x, y, z: 3 });
  tiles.push({ x: 13, y: 7, z: 4 });
  return tiles.map(({ x, y, z }) => ({ x: y, y: x, z }));
}

