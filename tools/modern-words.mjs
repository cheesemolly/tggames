/**
 * Формы слов для Wordle: в его русском словаре догадок есть падежи и множественное число («абазе», «абазу»),
 * поэтому и у новых слов принимаются самые ходовые пятибуквенные формы.
 */
export const WORDLE_FORMS = list(`
  сайты сайта сайте блоги блога блоге лайки лайка дроны дрона файлы файла клики клика фейки офисы офиса офисе
  кейсы треки скины роллы квизы спама хайпа ботов багов мемов читов чатов
`);

/** Слова списков: all — всё, что принимается (без грубого), known — то, что можно загадывать (без мрачного). */
export function lists() {
  const rude = new Set(RUDE.map(norm));
  const avoid = new Set(AVOID.map(norm));
  const ok = (w) => /^[а-я]{2,}$/.test(w) && !rude.has(w);
  const known = [...new Set([...KNOWN_EXTRA, ...KNOWN].map(norm))].filter((w) => ok(w) && !avoid.has(w)).sort();
  const all = [...new Set([...known, ...BONUS_EXTRA.map(norm), ...RARE.map(norm)])].filter(ok).sort();
  return { all, known };
}

/** Можно ли составить word из букв source (каждая буква — не больше, чем в source). */
function canCompose(word, source) {
  const have = new Map();
  for (const ch of source) have.set(ch, (have.get(ch) ?? 0) + 1);
  for (const ch of word) {
    const left = (have.get(ch) ?? 0) - 1;
    if (left < 0) return false;
    have.set(ch, left);
  }
  return true;
}

/** Филворд: бонусные слова — 3–9 букв без «ъ» (на поле 8×8 длиннее не встать), слова для поля — из известных. */
export function forBoggle(main, { all, known }) {
  const have = new Set(main.words);
  const fits = (w) => w.length >= 3 && w.length <= 9 && !w.includes('ъ');
  const words = all.filter((w) => fits(w) && !have.has(w));
  const bank = new Set(main.common);
  const common = known.filter((w) => fits(w) && !bank.has(w) && (have.has(w) || words.includes(w)));
  return { words, common };
}

/** Эрудит: слова от 3 до 15 букв (двухбуквенные там — отдельный выверенный список), частые — словарь слабого бота. */
export function forErudit(main, { all, known }) {
  const have = new Set(main.words);
  const fits = (w) => w.length >= 3 && w.length <= 15;
  const words = all.filter((w) => fits(w) && !have.has(w));
  const bank = new Set(main.common);
  const common = known.filter((w) => fits(w) && !bank.has(w) && (have.has(w) || words.includes(w)));
  return { words, common };
}

/** Wordle на русском: пятибуквенные слова; загадки — из известных, догадки — все и ходовые формы. */
export function forWordle(main, { all, known }) {
  const answersHave = new Set(main.answers);
  const allowedHave = new Set([...main.answers, ...main.allowed]);
  const five = (w) => w.length === 5;
  const answers = known.filter((w) => five(w) && !answersHave.has(w));
  const fresh = new Set(answers);
  const allowed = [...new Set([...all, ...WORDLE_FORMS.map(norm)])].filter((w) => five(w) && !allowedHave.has(w) && !fresh.has(w)).sort();
  return { answers, allowed };
}

/** «Слова из слова»: для каждого уровня — новые слова, которые складываются из букв его слова. */
export function forWords(levels, { all }) {
  return levels.map((level) => {
    const have = new Set([level.word, ...level.common, ...level.rare]);
    return all.filter((w) => w.length >= 3 && !have.has(w) && canCompose(w, level.word));
  });
}

const read = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const text = (data) => `${JSON.stringify(data)}\n`;

/** Все добавки: [[путь от корня проекта, текст файла]…]. */
export function build() {
  const sets = lists();
  return [
    ['games/boggle/words/ru-modern.json', text(forBoggle(read('../games/boggle/words/ru.json'), sets))],
    ['games/erudit/words/ru-modern.json', text(forErudit(read('../games/erudit/words/ru.json'), sets))],
    ['games/wordle/words/ru-modern.json', text(forWordle(read('../games/wordle/words/ru.json'), sets))],
    ['games/words/modern.json', text(forWords(read('../games/words/levels.json'), sets))],
  ];
}

function main() {
  const dry = process.argv.includes('--dry');
  const { all, known } = lists();
  console.log(`слов в списках: ${all.length}, из них известных: ${known.length}`);
  for (const [path, body] of build()) {
    const data = JSON.parse(body);
    const info = Array.isArray(data)
      ? `уровней с новыми словами ${data.filter((l) => l.length).length} из ${data.length}, слов ${data.reduce((n, l) => n + l.length, 0)}`
      : Object.entries(data).map(([k, v]) => `${k}: ${v.length}`).join(', ');
    console.log(`${path} — ${info}, ${(body.length / 1024).toFixed(1)} КБ`);
    if (!dry) writeFileSync(new URL(`../${path}`, import.meta.url), body);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
